import numpy as np
a = np.arange(10)
print("a =", a)
# 第 1 例：切片
print(a[2:5])    # 包含下标2 3 4，从2开始取，默认差1
print(a[::2])    # 从0开始取，每个差2
print(a[::-1])   # 负数代表从右往左走
# 第 2 例：切片是"视图"不是"复印件"
b = a[2:5]       # b 是 a 的一小段
b[0] = 99        # 只改了 b 的第一个数
print("a =", a)  # a 变了，99 出现在 a 里 切片不复制数据，它是同一块内存的另一个名字
# 第 3 例：比较运算也是整块运算
c = a > 5
print("c =", c)          # 比较的真假是布尔类型
print("c.dtype =", c.dtype)
# 第 4 例：布尔数组当"筛子"
print(a[c])      # 只输出了大于五的数
print(a[a > 5])  # 两行合成一行的写法，效果一样
# 第 5 例：组合条件
print(a[(a > 2) & (a < 7)])   # 拿到了2到7之间的数
# 把下面这行的注释去掉跑一次，看报什么错，看完重新注释掉
#print(a[a > 2 and a < 7])    and 问全班“整体过没过”，& 逐个学生问“两科都过没过”。布尔筛子要的是后者
# 第 6 例：数一数有几个满足
print((a > 5).sum())       # 求和
# 第 7 例：花式索引——按名单取人
print(a[[0, 2, 4]])        # 取特定顺序的数
print(a[[4, 2, 0]])
# 第 8 例：布尔筛子还能反过来当"印章"
a[a > 5] = 0
print("a =", a)            # 大于 5 的那些数现在是0
